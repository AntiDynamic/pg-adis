// Helper function to get users by city
export function getUsersByCity(city: string): MockUserWithPreferences[] {
  const cityLower = city.toLowerCase();
  const users = mockUsers.filter((user) => user.profile.city.toLowerCase() === cityLower);
  console.log(`getUsersByCity("${city}") found ${users.length} users`);
  return users;
}

// Helper function to get users by area
export function getUsersByArea(city: string, area: string): MockUserWithPreferences[] {
  const cityLower = city.toLowerCase();
  const areaLower = area.toLowerCase();
  const users = mockUsers.filter(
    (user) =>
      user.profile.city.toLowerCase() === cityLower &&
      user.preferences.preferredAreas.some((a) =>
        a.toLowerCase().includes(areaLower)
      )
  );
  console.log(`getUsersByArea("${city}", "${area}") found ${users.length} users`);
  return users;
}

// Helper function to get users within budget range
export function getUsersByBudgetRange(
  users: MockUserWithPreferences[],
  minBudget: number,
  maxBudget: number
): MockUserWithPreferences[] {
  return users.filter(
    (user) =>
      !(user.preferences.budgetMax < minBudget || user.preferences.budgetMin > maxBudget)
  );
}
